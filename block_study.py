"""Block organisation study (review section 3.3): does the block length change the selection?

    python block_study.py [--npz assignment_data.npz] [--mode wx|w]   # results/block_study_<mode>.md, fig11

--mode wx (default, primary): W and X both quantized, X with the same block length down its
columns; --mode w: weights only.

K = 100, so only the number of blocks per row sets the cost: block lengths 25-33 all mean 4
scales per row. Each format pays its own scale width: 8 bits (E8M0) for the MX formats, 4 bits
for BFP (g|4|5). bits/element = 6 + (blocks per row) * scale_bits / 100. The class MX block is
32 (4 blocks/row, 6.32 bits); BFP6 32|4|5 also has 4 blocks/row (6.16 bits), and the 16|4|5
comparison layout 7 (6.28 bits). Held-out Y error, ocp
and opt.  The second table compares formats at EQUAL storage, which is the fair comparison.
"""
import argparse
import os

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt   # noqa: E402

import selector as S              # noqa: E402
import selector_suite as T        # noqa: E402
from formats import FORMATS, quantize, quantize_X, split_X, blocks, layout, floor_log2   # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = list(FORMATS)
SHORT = {"MXFP6_E3M2": "E3M2", "MXFP6_E2M3": "E2M3", "MXFP6_E4M1": "E4M1", "MXINT6": "MXINT6", "BFP6": "BFP6"}
COL = {"MXFP6_E2M3": "#2a78d6", "BFP6": "#eb6834", "MXINT6": "#1baf7a", "MXFP6_E3M2": "#eda100", "MXFP6_E4M1": "#e87ba4"}
INK, INK2, GRID, SURF = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
LENGTHS = [100, 50, 34, 32, 25, 20, 17, 16, 13, 10, 8, 5, 4, 2]  # -> 1, 2, 3, 4, 4, 5, 6, 7, 8, 10, 13, 20, 25, 50 blocks/row
# 32 = the class layouts (blocks 32, 32, 32 and a tail of 4); 16 = BFP 16|4|5, the comparison layout


MODE = "wx"


def yerr(W, Xe, name, L, pol):
    Wq = quantize(W, name, block=L, policy=pol)[0]
    Xq = quantize_X(Xe, name, block=L, policy=pol)[0] if MODE == "wx" else Xe
    return 100 * np.linalg.norm(W @ Xe - Wq @ Xq) / np.linalg.norm(W @ Xe)


def rho(W, L):
    num = 0.0
    for sl in blocks(W.shape[1], L):
        B = np.abs(W[:, sl])
        mx = B.max(1)
        num += ((B > 0).sum(1) * 4.0 ** floor_log2(np.where(mx > 0, mx, 1.0)) * (mx > 0)).sum()
    return num / (W ** 2).sum()


def study(W, X):
    _, Xe = split_X(X)
    res = {}
    for L in LENGTHS:
        nb = len(blocks(W.shape[1], L))
        for n in NAMES:
            bits = 6 + nb * layout(n)["scale_bits"] / W.shape[1]
            res[n, L] = (nb, bits, yerr(W, Xe, n, L, "ocp"), yerr(W, Xe, n, L, "opt"))
    return res


def frontier(res, budgets):
    """Best (format, block length) whose storage fits each bits/element budget."""
    out = []
    for b in budgets:
        ok = [(v[2], n, L, v[1]) for (n, L), v in res.items() if v[1] <= b + 1e-9]
        out.append((b, min(ok)) if ok else (b, None))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--npz", default=None)
    ap.add_argument("--mode", default="wx", choices=["wx", "w"])
    a = ap.parse_args()
    global MODE
    MODE = a.mode
    W = np.load(os.path.join(HERE, "data", "W_C.npy")).astype(np.float64)
    X = np.load(os.path.join(HERE, "data", "X_cal.npy")).astype(np.float64)
    res = study(W, X)
    md = ["<!-- generated by block_study.py; do not edit by hand -->", "# Block organisation (dataset C, 6-bit elements)", "",
          "Mode: " + ("W and X both quantized (X with the same block length, down its columns)." if MODE == "wx"
                      else "weights only quantized, X in full precision."), "",
          "Held-out Y error % (class rule `ocp`; `opt` in brackets for the integer formats). MX formats pay 8 bits per scale, "
          "BFP 4 bits. **Bold** = the class layouts (block 32 for every format).", "",
          "| block length | blocks/row | MX bits/elem | BFP bits/elem | " + " | ".join(SHORT[n] for n in NAMES) + " | winner (same length) | ρ |",
          "|---|---|---|---|" + "---|" * len(NAMES) + "---|---|"]
    for L in LENGTHS:
        nb = res[NAMES[0], L][0]
        cells = []
        for n in NAMES:
            v = res[n, L]
            s = f"{v[2]:.3f}" + (f" [{v[3]:.3f}]" if n in ("MXINT6", "BFP6") else "")
            if L == layout(n)["block"]:
                s = f"**{s}**"
            cells.append(s)
        win = min(NAMES, key=lambda n: res[n, L][2])
        md.append(f"| {L} | {nb} | {6 + nb * 0.08:.2f} | {6 + nb * 0.04:.2f} | " + " | ".join(cells) +
                  f" | {SHORT[win]} | {rho(W, L):.2f} |")
    budgets = [6.04, 6.08, 6.16, 6.24, 6.28, 6.32, 6.40, 6.50, 6.64, 6.80, 7.0, 8.0]
    md += ["", "## Equal storage: the best format and block length within each bits/element budget (class rule)", "",
           "| budget (bits/elem) | best | block length | bits used | held-out Y err % | best MX format (8-bit scale) | best E2M3 |",
           "|---|---|---|---|---|---|---|"]
    for b, best in frontier(res, budgets):
        mx = [(v[2], n, L) for (n, L), v in res.items() if n != "BFP6" and v[1] <= b + 1e-9]
        e2 = [(v[2], L) for (n, L), v in res.items() if n == "MXFP6_E2M3" and v[1] <= b + 1e-9]
        mxs = f"{SHORT[min(mx)[1]]} L={min(mx)[2]} ({min(mx)[0]:.3f})" if mx else "none fits"
        e2s = f"L={min(e2)[1]} ({min(e2)[0]:.3f})" if e2 else "none fits"
        md.append(f"| {b:.2f} | {SHORT[best[1]]} | {best[2]} | {best[3]:.2f} | {best[0]:.3f} | {mxs} | {e2s} |")
    # A-E: winner at the class layouts vs at equal budget 6.32
    p = T.find_npz(a.npz)
    if p:
        md += ["", "## Datasets A–E: best choice at 6.32 bits/element when the block length is free (class rule)", "",
               "| dataset | class layouts winner | best (format, length) within 6.32 bits | error % | class-layout winner error % |",
               "|---|---|---|---|---|"]
        with np.load(p) as d:
            Xa = d["X_cal"].astype(np.float64)
            for k in "ABCDE":
                Wk = d["W_" + k].astype(np.float64)
                rk = study(Wk, Xa)
                _, Xe = split_X(Xa)
                cls = {}
                for n in NAMES:
                    L = layout(n)["block"]
                    nb = len(blocks(100, L))
                    cls[n] = yerr(Wk, Xe, n, L, "ocp")
                    rk[n, L] = (nb, 6 + nb * layout(n)["scale_bits"] / 100, cls[n], None)
                cw = min(cls, key=cls.get)
                bb = frontier(rk, [6.32])[0][1]
                md.append(f"| {k} | {SHORT[cw]} | {SHORT[bb[1]]}, L={bb[2]} ({bb[3]:.2f} bits) | {bb[0]:.3f} | {cls[cw]:.3f} |")
    if p and MODE == "w":
        md += ["", "## Per-block mixed MX formats (excluded by A7; only to answer \"would it help?\")", "",
               "Each 32-block takes whichever of the four MX formats has the smallest diag-H error (H from the even "
               "columns); +2 bits per block = 6.40 bits/element. Held-out Y error % against the best single format.", "",
               "| dataset | best single format | its error % | per-block mix % | relative reduction |", "|---|---|---|---|---|"]
        with np.load(p) as d:
            Xa = d["X_cal"].astype(np.float64)
            Xf, Xe = split_X(Xa)
            h = (Xf ** 2).sum(1)
            for k in "ABCDE":
                Wk = d["W_" + k].astype(np.float64)
                Q = {n: quantize(Wk, n)[0] for n in NAMES}
                err = {n: 100 * np.linalg.norm((Wk - Q[n]) @ Xe) / np.linalg.norm(Wk @ Xe) for n in NAMES}
                mxs = [n for n in NAMES if n != "BFP6"]
                Wm = np.empty_like(Wk)
                for sl in blocks(Wk.shape[1], 32):
                    pick = np.stack([(((Wk[:, sl] - Q[n][:, sl]) ** 2) * h[sl]).sum(1) for n in mxs]).argmin(0)
                    for i, n in enumerate(mxs):
                        Wm[pick == i, sl] = Q[n][pick == i, sl]
                em = 100 * np.linalg.norm((Wk - Wm) @ Xe) / np.linalg.norm(Wk @ Xe)
                b = min(err, key=err.get)
                md.append(f"| {k} | {SHORT[b]} | {err[b]:.3f} | {em:.3f} | {100 * (err[b] - em) / err[b]:.1f}% |")
    md += ["", "ρ = Σ n_nz·4^F / Σw² for that block length (the integer error is ρ·4⁻⁴/12): shorter blocks put each "
           "block maximum closer to its values, so ρ falls and the integer grids gain; FP error is relative to each "
           "value's own binade and only gains through fewer flushed values.", ""]
    with open(os.path.join(HERE, "results", f"block_study_{MODE}.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    # figure: error vs bits/element per format
    fig, ax = plt.subplots(figsize=(6.4, 4.0), facecolor=SURF)
    ax.set_facecolor(SURF)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.tick_params(colors=INK2, labelsize=8)
    ax.grid(True, color=GRID, lw=0.8)
    for n in ("MXFP6_E2M3", "BFP6", "MXINT6", "MXFP6_E3M2"):
        pts = sorted({res[n, L][1]: min(res[n, L2][2] for L2 in LENGTHS if res[n, L2][1] == res[n, L][1])
                      for L in LENGTHS}.items())
        pts = [q for q in pts if q[0] <= 7.05]
        ax.plot([q[0] for q in pts], [q[1] for q in pts], color=COL[n], lw=2, marker="o", markersize=4,
                markeredgecolor=SURF, label=SHORT[n])
    for n, L in (("MXFP6_E2M3", 32), ("BFP6", 32), ("MXINT6", 32)):
        ax.scatter(res[n, L][1], res[n, L][2], s=90, facecolor="none", edgecolor=INK, lw=1.2, zorder=4)
    ax.set_xlabel("storage (bits per element, scales included)", fontsize=9, color=INK)
    ax.set_ylabel("held-out Y error (%, class rule)", fontsize=9, color=INK)
    ax.set_title("Block length as a storage trade-off (circles: class layouts)", fontsize=10, color=INK, loc="left")
    ax.legend(frameon=False, fontsize=8, labelcolor=INK)
    fig.tight_layout()
    fig.savefig(os.path.join(HERE, "figures", "fig11_block_tradeoff.png" if MODE == "wx" else "fig11_block_tradeoff_w.png"),
                dpi=160, facecolor=SURF)
    print(f"wrote results/block_study_{MODE}.md and fig11")


if __name__ == "__main__":
    main()
