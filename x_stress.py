"""Does the selection hold up when the activations change?  (datasets A-E, 6-bit)

    python x_stress.py --npz assignment_data.npz      # results/x_stress.md (about 1 min)

1. For each dataset and each activation family (the real X_cal, bootstrap resamples of its
   columns, and every synthetic family in selector_suite.XKINDS, 5 seeds each): the held-out
   winner under the class rule, its margin, and how often three selectors find it
   (exact sketch with H from the fit columns; weights only; certified full-H row sample).
2. Shift: the format is chosen ONCE with the real X_cal (as we must before seeing the
   graders' X_test), then evaluated on X_test drawn from each family.  Regret of that fixed
   choice against the best format for that X_test.
"""
import argparse
import os

import numpy as np

import selector as S
import selector_suite as T
from formats import FORMATS, quantize, split_X

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = list(FORMATS)
SHORT = {"MXFP6_E3M2": "E3M2", "MXFP6_E2M3": "E2M3", "MXFP6_E4M1": "E4M1", "MXINT6": "MXINT6", "BFP6": "BFP6"}
SEEDS = 5


def yerrs(W, Xe):
    sig = np.linalg.norm(W @ Xe)
    return {n: 100 * np.linalg.norm((W - quantize(W, n)[0]) @ Xe) / sig for n in NAMES}


def families(Xcal, seed):
    rng = np.random.default_rng(seed)
    out = {"X_cal (real)": Xcal if seed == 0 else None,
           "X_cal bootstrap": Xcal[:, rng.integers(0, Xcal.shape[1], Xcal.shape[1])]}
    for k in T.XKINDS:
        out[k] = T._x(np.random.default_rng(1000 * seed + T.XKINDS.index(k)), Xcal.shape[0], k)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--npz", default=None)
    a = ap.parse_args()
    p = T.find_npz(a.npz)
    with np.load(p) as d:
        Xcal = d["X_cal"].astype(np.float64)
        Ws = {k: d["W_" + k].astype(np.float64) for k in "ABCDE"}
    md = ["<!-- generated by x_stress.py; do not edit by hand -->", "# Selection under different activations (datasets A–E)", "",
          f"Class rule, weights only quantized, held-out Y error on the odd columns of each X; {SEEDS} seeds per synthetic family. "
          "Winner (seeds won); margin = runner-up − winner in pp (mean); then how often each selector picks the held-out winner: "
          "**sketch_h** (exact, H from the even columns), **weights** (exact weight error, X ignored), "
          "**rows_y** (certified full-H row sample).", ""]
    shift = {}
    for k, W in Ws.items():
        md += [f"## Dataset {k}", "", "| X family | winner | margin pp | errors E3M2 / E2M3 / E4M1 / MXINT6 / BFP6 | sketch_h | weights | rows_y |",
               "|---|---|---|---|---|---|---|"]
        # the X_cal-based choice used in the shift test
        hc = (split_X(Xcal)[0] ** 2).sum(1)
        sc = S.sketch_select(W, hc)
        choice = min(sc, key=sc.get)
        stats = {}
        for seed in range(SEEDS):
            for name, X in families(Xcal, seed).items():
                if X is None:
                    continue
                Xf, Xe = split_X(X)
                h = (Xf ** 2).sum(1)
                e = yerrs(W, Xe)
                best = min(e, key=e.get)
                srt = sorted(e.values())
                picks = {}
                for lab, fn in (("sketch_h", lambda: S.sketch_select(W, h)), ("weights", lambda: S.sketch_select(W)),
                                ("rows_y", lambda: S.certified_rows_y(W, X=Xf))):
                    s_ = fn()
                    picks[lab] = min(s_, key=s_.get) == best
                st = stats.setdefault(name, {"wins": [], "margin": [], "err": [], "sketch_h": [], "weights": [], "rows_y": [],
                                             "shift": []})
                st["wins"].append(best)
                st["margin"].append(srt[1] - srt[0])
                st["err"].append([e[n] for n in NAMES])
                for lab in picks:
                    st[lab].append(picks[lab])
                st["shift"].append(10 * np.log10((e[choice] / e[best]) ** 2))
        for name, st in stats.items():
            w = max(set(st["wins"]), key=st["wins"].count)
            err = np.mean(st["err"], 0)
            md.append(f"| {name} | {SHORT[w]} ({st['wins'].count(w)}/{len(st['wins'])}) | {np.mean(st['margin']):.2f} | "
                      + " / ".join(f"{v:.2f}" for v in err) + " | "
                      + " | ".join(f"{100 * np.mean(st[lab]):.0f}%" for lab in ("sketch_h", "weights", "rows_y")) + " |")
        shift[k] = (choice, {name: (np.mean(st["shift"]), np.max(st["shift"]), st["wins"]) for name, st in stats.items()})
        md.append("")
    md += ["## Shift: choose once with the real X_cal, evaluate on a different X_test", "",
           "Regret (dB of Y error power) of the X_cal choice against the best format for that X_test; mean / max over seeds.", "",
           "| X_test family | " + " | ".join(f"{k} (chose {SHORT[shift[k][0]]})" for k in shift) + " |",
           "|---|" + "---|" * len(shift)]
    for name in shift["A"][1]:
        md.append(f"| {name} | " + " | ".join(f"{shift[k][1][name][0]:.3f} / {shift[k][1][name][1]:.3f}" for k in shift) + " |")
    with open(os.path.join(HERE, "results", "x_stress.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print("wrote results/x_stress.md")


if __name__ == "__main__":
    main()
